// 마지막으로 본 판(seen) 뒤에 나온 판들. 이미 최신이면 빈 배열
// 본 기록이 없거나 목록에 없는 값이면 최근 CATCH_UP 판까지 보여 준다 — 판 기록이 생기기 전부터 쓰던 사람은 기록이 없어서,
// 최신 한 판만 보여 주면 그동안 쌓인 변경을 놓친다(2026-10-13 제보). 전부 쏟아내지는 않는다(내역이 길어지면 처음 온 사람에게 너무 길다)
const CATCH_UP = 5;
export function changesSince(seen) {
  if (seen === APP_VERSION) return [];
  const idx = CHANGELOG.findIndex((c) => c.v === seen);
  return idx === -1 ? CHANGELOG.slice(0, CATCH_UP) : CHANGELOG.slice(0, idx);
}

// 서버에 올라와 있는 version.js 본문에서 판 번호를 읽는다(열어 둔 탭이 새 판을 알아채는 데 쓴다). 못 읽으면 null
export const versionIn = (text) => /APP_VERSION = '([^']+)'/.exec(String(text))?.[1] ?? null;
